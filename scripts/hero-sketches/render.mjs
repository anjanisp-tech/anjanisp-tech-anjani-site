// scripts/hero-sketches/render.mjs — turns sketch SVGs into the PNGs the site
// shows, checks each one, and rewrites src/data/heroImages.ts from what passed.
//
//   node scripts/hero-sketches/render.mjs            render + check every svg/*.svg
//   node scripts/hero-sketches/render.mjs --check    check public/hero only, write nothing
//
// The automatic look check (the only gate for fully automatic new-post sketches):
//   1. it renders (sharp can read the SVG and write a PNG)
//   2. it is exactly 1200x630
//   3. it is not blank: the picture is not one flat colour
//   4. it has enough line work: at least 1.2% of pixels are clearly brighter
//      than the navy ground, and at least 0.05% are teal (the idea's accent)
// A sketch that fails is NOT written to public/hero, so its post keeps the
// drawn title card. Exit code 1 if anything failed, so a scheduled task can see it.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const SVG_DIR = path.join(here, 'svg');
const HERO_DIR = path.join(root, 'public', 'hero');
const LIST = path.join(root, 'src', 'data', 'heroImages.ts');
const checkOnly = process.argv.includes('--check');

export async function checkPng(buf, { strict = true } = {}) {
  const img = sharp(buf);
  const meta = await img.metadata();
  if (meta.width !== 1200 || meta.height !== 630) return { ok: false, why: `size ${meta.width}x${meta.height}` };
  const { data, info } = await img.removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const n = info.width * info.height;
  let bright = 0, teal = 0, min = 255, max = 0;
  for (let i = 0; i < data.length; i += 3) {
    const r = data[i], g = data[i + 1], b = data[i + 2];
    const l = (r * 299 + g * 587 + b * 114) / 1000;
    if (l < min) min = l;
    if (l > max) max = l;
    if (l > 70) bright++;
    if (g > 130 && g - r > 60 && b > 100) teal++;
  }
  if (max - min < 40) return { ok: false, why: 'blank (one flat colour)' };
  const lineShare = bright / n, tealShare = teal / n;
  if (!strict) return { ok: true, lineShare, tealShare };
  if (lineShare < 0.012) return { ok: false, why: `too little line work (${(lineShare * 100).toFixed(2)}%)` };
  if (tealShare < 0.0005) return { ok: false, why: `no teal accent (${(tealShare * 100).toFixed(2)}%)` };
  return { ok: true, lineShare, tealShare };
}

function writeList(keys) {
  const body = keys.sort().map((k) => `  '${k}',`).join('\n');
  fs.writeFileSync(LIST, `// src/data/heroImages.ts — which posts and case studies have an idea sketch at
// public/hero/<kind>-<slug>.png. GENERATED by scripts/hero-sketches/render.mjs
// from that folder; do not edit by hand.
//
// Used by the Writing and Case Studies pages, the post pages, and api/_og.ts
// (the share image). A slug NOT listed has no sketch yet: the page shows the
// post's own cover art if it has one, and the share image falls back to the
// drawn title card. Never blank.

export const HERO_IMAGES: ReadonlySet<string> = new Set([
${body}
]);

export type HeroKind = 'blog' | 'case';

/** Site path of the sketch for this post, or '' if it has none. */
export function heroPath(kind: HeroKind, slug: string): string {
  const key = \`\${kind}-\${slug}\`;
  return HERO_IMAGES.has(key) ? \`/hero/\${key}.png\` : '';
}
`);
}

async function main() {
  fs.mkdirSync(HERO_DIR, { recursive: true });
  let failed = 0;
  if (!checkOnly) {
    for (const f of fs.readdirSync(SVG_DIR).filter((x) => x.endsWith('.svg')).sort()) {
      const key = f.replace(/\.svg$/, '');
      let png;
      try {
        png = await sharp(fs.readFileSync(path.join(SVG_DIR, f))).png({ compressionLevel: 9, palette: true, quality: 90 }).toBuffer();
      } catch (e) {
        console.log(`FAIL ${key}: does not render (${e.message})`); failed++; continue;
      }
      const c = await checkPng(png);
      if (!c.ok) { console.log(`FAIL ${key}: ${c.why}`); failed++; continue; }
      fs.writeFileSync(path.join(HERO_DIR, key + '.png'), png);
      console.log(`ok   ${key}  ${(png.length / 1024).toFixed(0)} KB  lines ${(c.lineShare * 100).toFixed(1)}%  teal ${(c.tealShare * 100).toFixed(2)}%`);
    }
  }
  const keys = [];
  for (const f of fs.readdirSync(HERO_DIR).filter((x) => x.endsWith('.png'))) {
    // Pictures already live are re-checked for size and blankness only, so a
    // stricter accent rule can never quietly drop an approved sketch.
    const c = await checkPng(fs.readFileSync(path.join(HERO_DIR, f)), { strict: false });
    if (c.ok) keys.push(f.replace(/\.png$/, ''));
    else { console.log(`FAIL public/hero/${f}: ${c.why}`); failed++; }
  }
  if (!checkOnly) writeList(keys);
  console.log(`${keys.length} sketches pass${failed ? `, ${failed} failed` : ''}`);
  process.exit(failed ? 1 : 0);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
